// Single source of truth for the form. The browser renders it (via GET /config)
// and the submit Lambda validates against it, so frontend and backend rules
// can never drift apart. In the real platform this would come from AEM.

export type FieldType = 'text' | 'email' | 'select' | 'textarea' | 'file';

export interface FieldDefinition {
  name: string;
  label: string;
  type: FieldType;
  required: boolean;
  maxLength?: number;
  options?: { value: string; label: string }[];
  // File fields only
  accept?: string[];
  maxSizeBytes?: number;
}

export interface FormDefinition {
  id: string;
  title: string;
  fields: FieldDefinition[];
}

