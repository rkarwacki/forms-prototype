export function findField(form: FormDefinition, name: string): FieldDefinition | undefined {
  return form.fields.find((f) => f.name === name);
}

const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

// Upload keys are generated by the upload Lambda: uploads/<uuid>/<file name>.
// Only accepting this shape stops a submission from pointing at other objects.
export const UPLOAD_KEY_PATTERN = /^uploads\/[0-9a-f-]{36}\/[A-Za-z0-9._-]{1,100}$/;

// Returns field name -> error message. Empty object means valid.
export function validate(form: FormDefinition, data: Record<string, unknown>): Record<string, string> {
  const errors: Record<string, string> = {};

  for (const field of form.fields) {
    const raw = data[field.name];
    const value = typeof raw === 'string' ? raw.trim() : '';

    if (!value) {
      if (field.required) errors[field.name] = 'This field is required';
      continue;
    }
    if (field.maxLength && value.length > field.maxLength) {
      errors[field.name] = `Must be at most ${field.maxLength} characters`;
    } else if (field.type === 'email' && !EMAIL_PATTERN.test(value)) {
      errors[field.name] = 'Not a valid email address';
    } else if (field.options && !field.options.some((o) => o.value === value)) {
      errors[field.name] = 'Not an allowed option';
    } else if (field.type === 'file' && !UPLOAD_KEY_PATTERN.test(value)) {
      errors[field.name] = 'Not a valid upload reference';
    }
  }

  return errors;
}
